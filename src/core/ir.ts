/**
 * Netlist IR: a normalized, DOM-free view of the Yosys JSON.
 *
 * - Every module, port, cell and net keeps its source location (`src`).
 * - Cells get a stable ID that survives unrelated edits to the Verilog,
 *   so layout data stored separately can be matched after a re-import.
 */
import type { YosysBit, YosysDesign, YosysDirection, YosysModule } from './yosys-json';

export type Bit = YosysBit;

export interface SrcRange {
  file: string;
  startLine: number;
  startCol: number;
  endLine: number;
  endCol: number;
}

export interface IRPort {
  name: string;
  direction: YosysDirection;
  bits: Bit[];
  /** Index of bits[0] in the declared range, e.g. 4 for `[7:4]`. */
  offset: number;
  /** True for ascending ranges such as `[0:7]`. */
  upto: boolean;
}

export interface IRCell {
  /** Stable ID, unique within the module. */
  id: string;
  /** Name as Yosys reports it (may be auto-generated, e.g. `$t.v:3$add$1`). */
  name: string;
  /** True when the name was generated by Yosys rather than written by the designer. */
  hidden: boolean;
  /** Raw Yosys type, e.g. `$add` or a module name. */
  type: string;
  /** True when this cell instantiates a module of the design. */
  isInstance: boolean;
  /** For instances: the module name in the design (same as type). */
  moduleName?: string;
  parameters: Record<string, string>;
  directions: Record<string, YosysDirection>;
  connections: Record<string, Bit[]>;
  src: SrcRange[];
  /** Set by semantic transforms: the rule that produced this cell. */
  rule?: string;
  /** Extra drawing hints set by semantic transforms. */
  attrs?: Record<string, string | number | boolean>;
}

export interface IRNet {
  name: string;
  hidden: boolean;
  bits: Bit[];
  offset: number;
  upto: boolean;
  src: SrcRange[];
}

export interface IRModule {
  name: string;
  /** Human-friendly name (parameterized module names are shortened). */
  displayName: string;
  isTop: boolean;
  ports: IRPort[];
  cells: IRCell[];
  nets: IRNet[];
  src: SrcRange[];
  /** Set for blocks found by automatic partitioning: the module they were cut from. */
  auto?: { parent: string };
}

export interface IRDesign {
  modules: Record<string, IRModule>;
  top: string;
}

export interface HierarchyNode {
  /** Instance name; the top module uses its module name. */
  instance: string;
  module: string;
  children: HierarchyNode[];
}

/** Parse a Yosys `src` attribute such as `top.v:7.7-7.52|top.v:9.1-9.20`. */
export function parseSrc(src: string | undefined): SrcRange[] {
  if (!src) return [];
  const out: SrcRange[] = [];
  for (const part of src.split('|')) {
    const m = /^(.*):(\d+)(?:\.(\d+))?(?:-(\d+)(?:\.(\d+))?)?$/.exec(part.trim());
    if (!m) continue;
    const startLine = Number(m[2]);
    const startCol = m[3] ? Number(m[3]) : 1;
    const endLine = m[4] ? Number(m[4]) : startLine;
    const endCol = m[5] ? Number(m[5]) : startCol;
    out.push({ file: m[1], startLine, startCol, endLine, endCol });
  }
  return out;
}

/** Shorten `$paramod\adder\WIDTH=...` to `adder`. */
export function displayModuleName(name: string): string {
  if (name.startsWith('$paramod')) {
    const parts = name.split('\\').filter(Boolean);
    if (parts.length >= 2) return parts[1];
  }
  return name.replace(/^\\/, '');
}

const OUTPUT_PORTS = new Set(['Y', 'Q', 'X', 'CO', 'RD_DATA']);

function cellDirections(
  type: string,
  connections: Record<string, Bit[]>,
  given: Record<string, YosysDirection> | undefined,
): Record<string, YosysDirection> {
  const out: Record<string, YosysDirection> = {};
  for (const port of Object.keys(connections)) {
    out[port] = given?.[port] ?? (type.startsWith('$') && OUTPUT_PORTS.has(port) ? 'output' : 'input');
  }
  return out;
}

/** Extract the exact source text a range covers (used for stable IDs). */
function sourceText(sources: Record<string, string>, r: SrcRange | undefined): string | undefined {
  if (!r) return undefined;
  const text = sources[r.file] ?? sources[basename(r.file)];
  if (text === undefined) return undefined;
  const lines = text.split('\n');
  if (r.startLine === r.endLine) {
    return lines[r.startLine - 1]?.slice(r.startCol - 1, r.endCol - 1);
  }
  const chunk = [lines[r.startLine - 1]?.slice(r.startCol - 1) ?? ''];
  for (let l = r.startLine; l < r.endLine - 1; l++) chunk.push(lines[l] ?? '');
  chunk.push(lines[r.endLine - 1]?.slice(0, r.endCol - 1) ?? '');
  return chunk.join('\n');
}

function basename(path: string): string {
  const i = path.lastIndexOf('/');
  return i >= 0 ? path.slice(i + 1) : path;
}

function normalizeWhitespace(s: string): string {
  return s.replace(/\s+/g, ' ').trim();
}

/** Remove `//` and `/* *\/` comments (string literals are kept as they are). */
function stripComments(s: string): string {
  return s.replace(/"(?:\\.|[^"\\\n])*"|\/\/[^\n]*|\/\*[\s\S]*?\*\//g, (m) => (m.startsWith('"') ? m : ' '));
}

/**
 * Flip-flops and latches. Yosys gives the ones it infers from an always block the source range
 * of the whole block, so that text says nothing about which register a cell is.
 */
const REGISTER_CELL = /^\$(\w*dff\w*|\w*dlatch\w*|sr|ff)$/;

/** A process (always/initial block) as source text. */
const PROCESS_TEXT = /^(always(_ff|_comb|_latch)?|initial|final)\b/;

/**
 * The MUX of a case statement: a `$pmux`, or a `$mux` Yosys makes for a case with one item (or for
 * each item of a case whose items are signals, such as `case (1'b1)`).
 * Yosys gives it no source text of its own, and the values of its cases are constant inputs, so
 * an ID made of what it connects to changed with every edited table entry.
 */
function isCaseMux(type: string, name: string, expr: string | undefined): boolean {
  return !expr && (type === '$pmux' || (type === '$mux' && name.startsWith('$procmux$')));
}

/**
 * proc's wire for the value a process gives a signal: `$0\state[1:0]`. Its other wires, `$2\y[3:0]`,
 * carry the value at one level of the if/case nesting, numbered by the if and case statements of the
 * block that come before it: one more `if` in an earlier case item renumbers them all, so they name nothing.
 */
const STAGE_WIRE = /^(\$0\\.+?)(\[\d+(:\d+)?\])?$/;

/**
 * `$0\state`: the next-value wire of a process that carries exactly these bits, or a slice of one.
 * It names the case MUX that gives a register of a clocked block its next value, whose output has
 * no name of its own, and ends the path that names a MUX nested in it.
 */
function stageSignal(nets: IRNet[], bits: Bit[]): string | undefined {
  const nums = bits.filter((b): b is number => typeof b === 'number');
  if (nums.length === 0 || nums.length !== bits.length) return undefined;
  for (const n of nets) {
    const m = n.hidden ? STAGE_WIRE.exec(n.name) : null;
    const start = m ? n.bits.indexOf(nums[0]) : -1;
    if (!m || start < 0 || !nums.every((b, i) => n.bits[start + i] === b)) continue;
    return sliceLabel({ ...n, name: m[1] }, start, start + nums.length - 1);
  }
  return undefined;
}

/**
 * The name of the signal some bits carry: `q`, or `q[3:2]` for part of it, preferring a net
 * that has exactly these bits; otherwise the names of the nets they touch. Undefined when no
 * public net carries any of them.
 *
 * Several names may carry the same bits (`always @* light = state;` makes `light` another name
 * of `state`). The one the code that made the cell mentions is taken, so the name does not
 * change when such an alias is added or removed.
 */
function signalName(nets: IRNet[], bits: Bit[], code: string): string | undefined {
  const nums = bits.filter((b): b is number => typeof b === 'number');
  if (nums.length === 0) return undefined;
  const mentioned = (label: string) => {
    const name = label.replace(/\[\d+(:\d+)?\]$/, '');
    return new RegExp(`(^|[^\\w$])${name.replace(/[^\w]/g, '\\$&')}($|[^\\w$])`).test(code);
  };
  const pick = (labels: string[]) => labels.find(mentioned) ?? labels[0];
  const whole: string[] = [];
  const parts: string[] = [];
  if (nums.length === bits.length) {
    for (const n of nets) {
      if (n.hidden) continue;
      const start = n.bits.indexOf(nums[0]);
      if (start < 0 || !nums.every((b, i) => n.bits[start + i] === b)) continue;
      const label = sliceLabel(n, start, start + nums.length - 1);
      (label === n.name ? whole : parts).push(label);
    }
  }
  if (whole.length) return pick(whole);
  if (parts.length) return pick(parts);
  const names = new Set<string>();
  for (const n of nets) if (!n.hidden && n.bits.some((b) => typeof b === 'number' && nums.includes(b))) names.add(n.name);
  return names.size ? [...names].join('+') : undefined;
}

/**
 * `Q=q`: the signals the outputs of a cell drive, for its fingerprint ('' when none has a name).
 * `stages`: also name an output by the next-value wire of a process it drives (`Y=$0\state`), for case MUXes.
 */
function drivenSignals(
  nets: IRNet[],
  connections: Record<string, Bit[]>,
  directions: Record<string, YosysDirection>,
  code: string,
  stages = false,
): string {
  return Object.keys(connections)
    .filter((p) => directions[p] === 'output')
    .sort()
    .flatMap((p) => {
      const name = signalName(nets, connections[p], code) ?? (stages ? stageSignal(nets, connections[p]) : undefined);
      return name === undefined ? [] : [`${p}=${name}`];
    })
    .join(',');
}

/**
 * `Q=q`: what the register nearest downstream of a cell drives, following its outputs through the
 * cells they feed; undefined when no named register is reached in a few steps. When it serves
 * several, the first by name: another latch of the same block then renames it only if its name
 * comes first.
 */
function servedRegister(cells: IRCell[], readers: Map<number, number[]>, named: Map<number, string>, start: number): string | undefined {
  const seen = new Set([start]);
  let frontier = [start];
  for (let depth = 0; depth < 8 && frontier.length; depth++) {
    const next: number[] = [];
    const found = new Set<string>();
    for (const i of frontier) {
      const c = cells[i];
      for (const [p, bits] of Object.entries(c.connections)) {
        if (c.directions[p] !== 'output') continue;
        for (const b of bits) {
          for (const k of typeof b === 'number' ? (readers.get(b) ?? []) : []) {
            if (seen.has(k)) continue;
            seen.add(k);
            const drives = named.get(k);
            if (drives) found.add(drives);
            else next.push(k);
          }
        }
      }
    }
    if (found.size) return [...found].sort()[0];
    frontier = next;
  }
  return undefined;
}

/** The only cell input that reads the outputs of a cell, when one input of one cell reads them all. */
function soleReader(cells: IRCell[], readers: Map<number, number[]>, index: number): { cell: number; port: string } | undefined {
  const c = cells[index];
  let found: { cell: number; port: string } | undefined;
  for (const [p, bits] of Object.entries(c.connections)) {
    if (c.directions[p] !== 'output') continue;
    for (const b of bits) {
      if (typeof b !== 'number') continue;
      for (const k of readers.get(b) ?? []) {
        for (const [q, read] of Object.entries(cells[k].connections)) {
          if (cells[k].directions[q] === 'output' || !read.includes(b)) continue;
          if (found && (found.cell !== k || found.port !== q)) return undefined;
          found = { cell: k, port: q };
        }
      }
    }
  }
  return found;
}

function isMux(type: string): boolean {
  return type === '$mux' || type === '$pmux';
}

/** The cell whose output drives each bit (the first one, when several do). */
export function bitDrivers(cells: IRCell[]): Map<number, IRCell> {
  const out = new Map<number, IRCell>();
  for (const c of cells) {
    for (const [p, bits] of Object.entries(c.connections)) {
      if (c.directions[p] !== 'output') continue;
      for (const b of bits) if (typeof b === 'number' && !out.has(b)) out.set(b, c);
    }
  }
  return out;
}

/**
 * The value the select bit of a case compares the case expression with (`4'd7`, or `3'd0,3'd1` for
 * an item with two labels), when a compare drives it; undefined otherwise (a casez bit, own logic).
 */
function compareValue(drivers: Map<number, IRCell>, b: Bit, depth = 0): string | undefined {
  const c = typeof b === 'number' ? drivers.get(b) : undefined;
  if (!c || depth > 1) return undefined;
  if (c.type === '$eq' || c.type === '$eqx') {
    const k = [c.connections.B, c.connections.A].find((x) => x?.length && x.every((y) => typeof y !== 'number'));
    return k && formatConst(k);
  }
  if (c.type !== '$reduce_or' && c.type !== '$or' && c.type !== '$logic_or') return undefined;
  const labels = [...(c.connections.A ?? []), ...(c.connections.B ?? [])].map((x) => compareValue(drivers, x, depth + 1));
  return labels.length && labels.every(Boolean) ? labels.join(',') : undefined;
}

/**
 * The name of each case of a $pmux, from its select bits: the value the case is selected by, so that
 * it does not change when other cases are added, removed, reordered or given other values. The case
 * index when the select is not a compare, or when two cases have the same value. It names the
 * constants of a case table, and the case a nested case statement is in.
 */
export function caseNames(drivers: Map<number, IRCell>, select: Bit[]): string[] {
  const values = select.map((b) => compareValue(drivers, b));
  return values.map((v, k) => (v && values.indexOf(v) === values.lastIndexOf(v) ? v : String(k)));
}

/**
 * `[2'd2]`: the case of a MUX that the outputs of a cell feed through its B input, named by the value
 * the case compares with: a case of a $pmux (its index when there is no compare), or the one case of
 * a $mux whose select is a compare. '' for any other input.
 */
function caseSlot(drivers: Map<number, IRCell>, cell: IRCell, reader: IRCell, port: string): string {
  if (port !== 'B' || !isMux(reader.type)) return '';
  const outs = new Set<Bit>();
  for (const p of Object.keys(cell.connections)) {
    if (cell.directions[p] === 'output') for (const b of cell.connections[p]) if (typeof b === 'number') outs.add(b);
  }
  const k = Math.floor(reader.connections.B.findIndex((b) => outs.has(b)) / Math.max(1, reader.connections.A?.length ?? 1));
  if (reader.type === '$pmux') return `[${caseNames(drivers, reader.connections.S ?? [])[k] ?? k}]`;
  const s = reader.connections.S?.[0];
  const v = s === undefined ? undefined : compareValue(drivers, s);
  return v ? `[${v}]` : '';
}

/** True when source range `outer` holds `inner`, or when that cannot be told (a range is missing). */
function encloses(outer: SrcRange | undefined, inner: SrcRange | undefined): boolean {
  if (!outer || !inner || outer.file !== inner.file) return true;
  const atOrBefore = (l1: number, c1: number, l2: number, c2: number) => l1 < l2 || (l1 === l2 && c1 <= c2);
  return atOrBefore(outer.startLine, outer.startCol, inner.startLine, inner.startCol) && atOrBefore(inner.endLine, inner.endCol, outer.endLine, outer.endCol);
}

/**
 * True when two cells come from the same statement (Yosys gives a MUX the range of its if or case
 * last), or when that cannot be told.
 */
function sameRange(a: SrcRange | undefined, b: SrcRange | undefined): boolean {
  return encloses(a, b) && encloses(b, a);
}

/**
 * A $mux whose A input is undefined: in a combinational block, Yosys puts one around the value each
 * statement in a branch gives a signal (`x` when the branch is not taken). It is part of no statement.
 */
function undefinedDefault(c: IRCell): boolean {
  return c.type === '$mux' && !!c.connections.A?.length && c.connections.A.every((b) => b === 'x');
}

/** The cell that drives some bits, looking through undefined-default wrappers to the statement they wrap. */
function statementOf(drivers: Map<number, IRCell>, bits: Bit[] | undefined): IRCell | undefined {
  const driver = (x: Bit[] | undefined) => {
    const b = x?.find((y) => typeof y === 'number');
    return typeof b === 'number' ? drivers.get(b) : undefined;
  };
  let d = driver(bits);
  for (let n = 0; d && undefinedDefault(d) && n < 16; n++) d = driver(d.connections.B);
  return d;
}

/**
 * True when the value a MUX keeps when it selects nothing (its A input) comes from an earlier statement
 * that assigns the same signal, in the same block or, when `parent` (the range of a statement) is
 * given, in the same branch of that statement. That value comes through a wire of Yosys' own: a
 * signal with a name (`default: y = z;`) is not an earlier statement.
 */
function followsStatement(nets: IRNet[], drivers: Map<number, IRCell>, c: IRCell, parent?: SrcRange): boolean {
  if (!isMux(c.type) || signalName(nets, c.connections.A ?? [], '') !== undefined) return false;
  const d = statementOf(drivers, c.connections.A);
  const before = d?.src.at(-1);
  const own = c.src.at(-1);
  return !!d && isMux(d.type) && !!before && !!own && !encloses(before, own) && !encloses(own, before) && (!parent || encloses(parent, before));
}

/**
 * What the case or if of a MUX selects on: `op` for the compares of `case (op)`, `en` for `if (en)`,
 * `a+b` for `if (a && b)`; undefined for other cells.
 */
function selectSubject(nets: IRNet[], drivers: Map<number, IRCell>, c: IRCell): string | undefined {
  const subject = (bits: Bit[], depth: number): string | undefined => {
    const name = signalName(nets, bits, '');
    if (name || depth > 2) return name;
    const read = new Set<IRCell>();
    for (const b of bits) if (typeof b === 'number' && drivers.has(b)) read.add(drivers.get(b)!);
    const inputs = [...read].flatMap((d) =>
      Object.keys(d.connections)
        .filter((p) => d.directions[p] !== 'output')
        .sort()
        .flatMap((p) => d.connections[p].filter((b) => typeof b === 'number')),
    );
    return inputs.length ? subject(inputs, depth + 1) : undefined;
  };
  const s = isMux(c.type) ? c.connections.S : undefined;
  return s?.length ? subject(s.slice(0, 1), 0) : undefined;
}

function buildModule(
  name: string,
  m: YosysModule,
  allModules: Set<string>,
  sources: Record<string, string>,
): IRModule {
  const ports: IRPort[] = Object.entries(m.ports).map(([pname, p]) => ({
    name: pname,
    direction: p.direction,
    bits: p.bits,
    offset: p.offset ?? 0,
    upto: !!p.upto,
  }));

  const nets: IRNet[] = Object.entries(m.netnames).map(([nname, n]) => ({
    name: nname,
    hidden: !!n.hide_name,
    bits: n.bits,
    offset: n.offset ?? 0,
    upto: !!n.upto,
    src: parseSrc(n.attributes?.src),
  }));

  // bit -> public net name, used to build readable fingerprints.
  const bitName = new Map<number, string>();
  for (const n of nets) {
    if (n.hidden) continue;
    for (const b of n.bits) if (typeof b === 'number' && !bitName.has(b)) bitName.set(b, n.name);
  }

  /** Cells made of a whole always block that drive no named signal, with the signals they touch. */
  const helpers: { index: number; touched: string }[] = [];
  /** Registers named by the signals they drive (`$dlatch{Q=q}`), with those signals. */
  const namedRegisters = new Map<number, string>();
  /** Case MUXes whose output has no name, not even a stage wire (a case nested in another case or an if). */
  const unnamedCaseMuxes = new Set<number>();
  const cells: IRCell[] = Object.entries(m.cells).map(([cname, c], index) => {
    const hidden = !!c.hide_name || cname.startsWith('$');
    const src = parseSrc(c.attributes?.src);
    const directions = cellDirections(c.type, c.connections, c.port_directions);
    let base: string;
    if (!hidden) {
      base = cname;
    } else {
      // Fingerprint: type + the expression text it came from + named signals it touches.
      // Comments are not part of what a cell computes: adding one must not change its ID.
      const text = sourceText(sources, src[0]);
      const expr = text ? normalizeWhitespace(stripComments(text)) : undefined;
      // A register (or any cell made from a whole always block) is told apart by what it drives:
      // the block's text changes with every statement or comment in it, and is the same for every
      // register the block makes. Edits saved for `$dff{Q=q}` then survive changes to the block.
      // So is the MUX of a case statement (`$pmux{Y=seg}`): its inputs are the values of the case
      // table, and edits saved for it must survive a change to one of them.
      const caseMux = isCaseMux(c.type, cname, expr);
      // The code that made the cell, to pick among several names of the same bits: for a case MUX,
      // its case statement (Yosys gives it the position of an item, then the range of the statement).
      const code = caseMux ? stripComments(sourceText(sources, src[1]) ?? '') : (expr ?? '');
      const drives =
        REGISTER_CELL.test(c.type) || PROCESS_TEXT.test(expr ?? '') || caseMux
          ? drivenSignals(nets, c.connections, directions, code, caseMux)
          : '';
      const touched = Object.keys(c.connections)
        .sort()
        .map((p) => {
          const bits = c.connections[p];
          // A constant operand tells apart cells that read the same signals, such as the `sel == 2'd0`,
          // `sel == 2'd1`… compares of a case statement (Yosys gives them no source text). Without it
          // they differ only by Yosys' cell order, so after the case items are reordered an edit
          // saved for one of them would move or hide another. The constants of a case MUX are the
          // values of its table, which are edited: they are left out.
          if (bits.length > 0 && bits.every((b) => typeof b !== 'number')) return `${p}=${caseMux ? '' : formatConst(bits)}`;
          const names = new Set<string>();
          for (const b of bits) if (typeof b === 'number' && bitName.has(b)) names.add(bitName.get(b)!);
          return `${p}=${[...names].join('+')}`;
        })
        .join(',');
      base = `${c.type}{${drives || (expr ?? touched)}}`;
      if (drives && REGISTER_CELL.test(c.type)) namedRegisters.set(index, drives);
      else if (!drives && PROCESS_TEXT.test(expr ?? '')) helpers.push({ index, touched });
      else if (!drives && caseMux) unnamedCaseMuxes.add(index);
    }
    const isInstance = allModules.has(c.type);
    return {
      id: base,
      name: cname,
      hidden,
      type: c.type,
      isInstance,
      moduleName: isInstance ? c.type : undefined,
      parameters: c.parameters ?? {},
      directions,
      connections: c.connections,
      src,
    };
  });

  if (helpers.length || unnamedCaseMuxes.size) {
    const readers = new Map<number, number[]>();
    cells.forEach((c, i) => {
      for (const [p, bits] of Object.entries(c.connections)) {
        if (c.directions[p] === 'output') continue;
        for (const b of bits) {
          if (typeof b !== 'number') continue;
          const list = readers.get(b);
          if (list) list.push(i);
          else readers.set(b, [i]);
        }
      }
    });
    // The logic Yosys adds for the enable of a latch has the source range of the whole always block.
    // It is named by what it touches and the register it serves (`$not{A=en,Y=;Q=q}`) instead, so that
    // another statement in the block does not change its ID.
    for (const h of helpers) {
      const served = servedRegister(cells, readers, namedRegisters, h.index);
      if (served) cells[h.index].id = `${cells[h.index].type}{${h.touched};${served}}`;
    }
    // A case nested in another case or in an if drives a wire of Yosys' own (`$procmux$12_Y`, or `$2\y`,
    // numbered by the statements before it). Without its values, its fingerprint can be the same as that
    // of the other nested cases, and Yosys' cell order would tell them apart: one more item in one of
    // them could swap their IDs. It is named by the MUX inputs its value goes through to the first signal
    // with a name: `$pmux{Y>$pmux.B[2'd2]>$mux.A>Y=$0\y}` for a case in the item 2'd2 of a case in the
    // else of an if, or `$mux{Y>$mux.A>$mux.A>Y=$0\st}` for the chain of MUXes of a `case (1'b1)`.
    // An item is named by the value it compares with, so items added, removed or changed elsewhere
    // rename nothing.
    // The value also goes through the later statements of the block that assign the same signal
    // (`if (rst) y = 0;` after a case), as what they keep when they select nothing. Those are left out,
    // so that adding or removing one renames nothing. A statement that comes before or after another
    // one is named by what it selects on instead (`(op)`), to tell it from them.
    const drivers = bitDrivers(cells);
    const subject = (c: IRCell) => `(${selectSubject(nets, drivers, c) ?? ''})`;
    for (const i of unnamedCaseMuxes) {
      const path: string[] = [];
      const seen = new Set([i]);
      /** The cell whose outputs the next step reads. */
      let prev = cells[i];
      /** The last cell of the path that belongs to a statement (a wrapper stands for the statement it wraps). */
      let from = cells[i];
      const wrapped = undefinedDefault(from) ? statementOf(drivers, from.connections.B) : undefined;
      if (wrapped && isMux(wrapped.type)) from = wrapped;
      /** True after a step into a later statement: the cells from there on are not on the path. */
      let later = false;
      for (let feeds = soleReader(cells, readers, i); feeds && !seen.has(feeds.cell) && path.length < 16; ) {
        const r = cells[feeds.cell];
        const stmt = r.src.at(-1);
        const wrapper = undefinedDefault(r);
        seen.add(feeds.cell);
        if (feeds.port === 'A' && isMux(r.type) && !encloses(stmt, from.src.at(-1))) {
          if (!later) path.push(subject(from));
          later = true;
          from = r;
        } else if (!(later && wrapper)) {
          // Leaving a statement for the one around it: it may come after another one in the same branch.
          if (!later && !wrapper && !sameRange(stmt, from.src.at(-1)) && followsStatement(nets, drivers, from, stmt)) path.push(subject(from));
          path.push(`${r.type}.${feeds.port}${caseSlot(drivers, prev, r, feeds.port)}`);
          later = false;
          if (!wrapper) from = r;
        }
        const drives = drivenSignals(nets, r.connections, r.directions, '', true);
        if (drives) {
          if (!later && followsStatement(nets, drivers, r)) path.push(subject(r));
          cells[i].id = `${cells[i].type}{Y>${path.join('>')}>${drives}}`;
          break;
        }
        prev = r;
        feeds = soleReader(cells, readers, feeds.cell);
      }
    }
  }
  const used = new Map<string, number>();
  for (const c of cells) {
    const n = used.get(c.id) ?? 0;
    used.set(c.id, n + 1);
    if (n > 0) c.id = `${c.id}#${n}`;
  }

  return {
    name,
    displayName: displayModuleName(name),
    isTop: m.attributes?.top !== undefined && /1/.test(m.attributes.top),
    ports,
    cells,
    nets,
    src: parseSrc(m.attributes?.src),
  };
}

/**
 * Convert Yosys JSON into the IR.
 * @param sources file name -> Verilog text, used for stable IDs and code highlighting.
 */
export function buildDesign(json: YosysDesign, sources: Record<string, string> = {}): IRDesign {
  const names = new Set(Object.keys(json.modules));
  const modules: Record<string, IRModule> = {};
  for (const [name, m] of Object.entries(json.modules)) {
    // Skip blackbox / library cells Yosys may include.
    if (m.attributes?.blackbox && /1/.test(m.attributes.blackbox)) continue;
    modules[name] = buildModule(name, m, names, sources);
  }
  let top = Object.values(modules).find((m) => m.isTop)?.name;
  if (!top) {
    // Fall back to a module nobody instantiates.
    const instantiated = new Set<string>();
    for (const m of Object.values(modules)) for (const c of m.cells) if (c.isInstance) instantiated.add(c.type);
    top = Object.keys(modules).find((n) => !instantiated.has(n)) ?? Object.keys(modules)[0];
  }
  return { modules, top: top ?? '' };
}

export function buildHierarchy(design: IRDesign, moduleName = design.top, instance = moduleName, depth = 0): HierarchyNode {
  const m = design.modules[moduleName];
  const children: HierarchyNode[] = [];
  if (m && depth < 64) {
    for (const c of m.cells) {
      if (c.isInstance && design.modules[c.type]) children.push(buildHierarchy(design, c.type, c.name, depth + 1));
    }
  }
  return { instance, module: moduleName, children };
}

/** Bits driven from outside the module: its input and inout port bits. */
export function inputPortBits(m: IRModule): Set<number> {
  const out = new Set<number>();
  for (const p of m.ports) if (p.direction !== 'output') for (const b of p.bits) if (typeof b === 'number') out.add(b);
  return out;
}

/** Width of a port or net in bits. */
export function widthOf(x: { bits: Bit[] }): number {
  return x.bits.length;
}

/** `name[hi:lo]` for a slice of a net, or just `name` when it covers the whole net. */
export function sliceLabel(net: IRNet, lo: number, hi: number): string {
  if (lo === 0 && hi === net.bits.length - 1) return net.name;
  const a = net.upto ? net.offset + (net.bits.length - 1 - hi) : net.offset + hi;
  const b = net.upto ? net.offset + (net.bits.length - 1 - lo) : net.offset + lo;
  return a === b ? `${net.name}[${a}]` : `${net.name}[${a}:${b}]`;
}

/** Format constant bits (LSB first) the way designers write them: 4'd2, 1'b0, 3'bx01. */
export function formatConst(bits: Bit[]): string {
  const w = bits.length;
  if (bits.every((b) => b === '0' || b === '1')) {
    if (w === 1) return `1'b${bits[0]}`;
    let v = 0n;
    for (let i = w - 1; i >= 0; i--) v = (v << 1n) | (bits[i] === '1' ? 1n : 0n);
    return `${w}'d${v.toString()}`;
  }
  return `${w}'b${[...bits].reverse().join('')}`;
}
