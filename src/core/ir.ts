/**
 * Netlist IR: a normalized, DOM-free view of the Yosys JSON.
 *
 * - Every module, port, cell and net keeps its source location (`src`).
 * - Cells get a stable ID that survives unrelated edits to the Verilog,
 *   so layout data stored separately can be matched after a re-import.
 */
import type { YosysBit, YosysDesign, YosysDirection, YosysModule } from './yosys-json';

export type Bit = YosysBit;

export interface SrcRange {
  file: string;
  startLine: number;
  startCol: number;
  endLine: number;
  endCol: number;
}

export interface IRPort {
  name: string;
  direction: YosysDirection;
  bits: Bit[];
  /** Index of bits[0] in the declared range, e.g. 4 for `[7:4]`. */
  offset: number;
  /** True for ascending ranges such as `[0:7]`. */
  upto: boolean;
}

export interface IRCell {
  /** Stable ID, unique within the module. */
  id: string;
  /** Name as Yosys reports it (may be auto-generated, e.g. `$t.v:3$add$1`). */
  name: string;
  /** True when the name was generated by Yosys rather than written by the designer. */
  hidden: boolean;
  /** Raw Yosys type, e.g. `$add` or a module name. */
  type: string;
  /** True when this cell instantiates a module of the design. */
  isInstance: boolean;
  /** For instances: the module name in the design (same as type). */
  moduleName?: string;
  parameters: Record<string, string>;
  directions: Record<string, YosysDirection>;
  connections: Record<string, Bit[]>;
  src: SrcRange[];
  /** Set by semantic transforms: the rule that produced this cell. */
  rule?: string;
  /** Extra drawing hints set by semantic transforms. */
  attrs?: Record<string, string | number | boolean>;
}

export interface IRNet {
  name: string;
  hidden: boolean;
  bits: Bit[];
  offset: number;
  upto: boolean;
  src: SrcRange[];
}

export interface IRModule {
  name: string;
  /** Human-friendly name (parameterized module names are shortened). */
  displayName: string;
  isTop: boolean;
  ports: IRPort[];
  cells: IRCell[];
  nets: IRNet[];
  src: SrcRange[];
  /** Set for blocks found by automatic partitioning: the module they were cut from. */
  auto?: { parent: string };
}

export interface IRDesign {
  modules: Record<string, IRModule>;
  top: string;
}

export interface HierarchyNode {
  /** Instance name; the top module uses its module name. */
  instance: string;
  module: string;
  children: HierarchyNode[];
}

/** Parse a Yosys `src` attribute such as `top.v:7.7-7.52|top.v:9.1-9.20`. */
export function parseSrc(src: string | undefined): SrcRange[] {
  if (!src) return [];
  const out: SrcRange[] = [];
  for (const part of src.split('|')) {
    const m = /^(.*):(\d+)(?:\.(\d+))?(?:-(\d+)(?:\.(\d+))?)?$/.exec(part.trim());
    if (!m) continue;
    const startLine = Number(m[2]);
    const startCol = m[3] ? Number(m[3]) : 1;
    const endLine = m[4] ? Number(m[4]) : startLine;
    const endCol = m[5] ? Number(m[5]) : startCol;
    out.push({ file: m[1], startLine, startCol, endLine, endCol });
  }
  return out;
}

/** Shorten `$paramod\adder\WIDTH=...` to `adder`. */
export function displayModuleName(name: string): string {
  if (name.startsWith('$paramod')) {
    const parts = name.split('\\').filter(Boolean);
    if (parts.length >= 2) return parts[1];
  }
  return name.replace(/^\\/, '');
}

const OUTPUT_PORTS = new Set(['Y', 'Q', 'X', 'CO', 'RD_DATA']);

function cellDirections(
  type: string,
  connections: Record<string, Bit[]>,
  given: Record<string, YosysDirection> | undefined,
): Record<string, YosysDirection> {
  const out: Record<string, YosysDirection> = {};
  for (const port of Object.keys(connections)) {
    out[port] = given?.[port] ?? (type.startsWith('$') && OUTPUT_PORTS.has(port) ? 'output' : 'input');
  }
  return out;
}

/** Extract the exact source text a range covers (used for stable IDs). */
function sourceText(sources: Record<string, string>, r: SrcRange | undefined): string | undefined {
  if (!r) return undefined;
  const text = sources[r.file] ?? sources[basename(r.file)];
  if (text === undefined) return undefined;
  const lines = text.split('\n');
  if (r.startLine === r.endLine) {
    return lines[r.startLine - 1]?.slice(r.startCol - 1, r.endCol - 1);
  }
  const chunk = [lines[r.startLine - 1]?.slice(r.startCol - 1) ?? ''];
  for (let l = r.startLine; l < r.endLine - 1; l++) chunk.push(lines[l] ?? '');
  chunk.push(lines[r.endLine - 1]?.slice(0, r.endCol - 1) ?? '');
  return chunk.join('\n');
}

function basename(path: string): string {
  const i = path.lastIndexOf('/');
  return i >= 0 ? path.slice(i + 1) : path;
}

function normalizeWhitespace(s: string): string {
  return s.replace(/\s+/g, ' ').trim();
}

/** Remove `//` and `/* *\/` comments (string literals are kept as they are). */
function stripComments(s: string): string {
  return s.replace(/"(?:\\.|[^"\\\n])*"|\/\/[^\n]*|\/\*[\s\S]*?\*\//g, (m) => (m.startsWith('"') ? m : ' '));
}

/**
 * Flip-flops and latches. Yosys gives the ones it infers from an always block the source range
 * of the whole block, so that text says nothing about which register a cell is.
 */
const REGISTER_CELL = /^\$(\w*dff\w*|\w*dlatch\w*|sr|ff)$/;

/** A process (always/initial block) as source text. */
const PROCESS_TEXT = /^(always(_ff|_comb|_latch)?|initial|final)\b/;

/**
 * The name of the signal some bits carry: `q`, or `q[3:2]` for part of it, preferring a net
 * that has exactly these bits; otherwise the names of the nets they touch. Undefined when no
 * public net carries any of them.
 *
 * Several names may carry the same bits (`always @* light = state;` makes `light` another name
 * of `state`). The one the code that made the cell mentions is taken, so the name does not
 * change when such an alias is added or removed.
 */
function signalName(nets: IRNet[], bits: Bit[], code: string): string | undefined {
  const nums = bits.filter((b): b is number => typeof b === 'number');
  if (nums.length === 0) return undefined;
  const mentioned = (label: string) => {
    const name = label.replace(/\[\d+(:\d+)?\]$/, '');
    return new RegExp(`(^|[^\\w$])${name.replace(/[^\w]/g, '\\$&')}($|[^\\w$])`).test(code);
  };
  const pick = (labels: string[]) => labels.find(mentioned) ?? labels[0];
  const whole: string[] = [];
  const parts: string[] = [];
  if (nums.length === bits.length) {
    for (const n of nets) {
      if (n.hidden) continue;
      const start = n.bits.indexOf(nums[0]);
      if (start < 0 || !nums.every((b, i) => n.bits[start + i] === b)) continue;
      const label = sliceLabel(n, start, start + nums.length - 1);
      (label === n.name ? whole : parts).push(label);
    }
  }
  if (whole.length) return pick(whole);
  if (parts.length) return pick(parts);
  const names = new Set<string>();
  for (const n of nets) if (!n.hidden && n.bits.some((b) => typeof b === 'number' && nums.includes(b))) names.add(n.name);
  return names.size ? [...names].join('+') : undefined;
}

/** `Q=q`: the signals the outputs of a cell drive, for its fingerprint ('' when none has a name). */
function drivenSignals(
  nets: IRNet[],
  connections: Record<string, Bit[]>,
  directions: Record<string, YosysDirection>,
  code: string,
): string {
  return Object.keys(connections)
    .filter((p) => directions[p] === 'output')
    .sort()
    .flatMap((p) => {
      const name = signalName(nets, connections[p], code);
      return name === undefined ? [] : [`${p}=${name}`];
    })
    .join(',');
}

function buildModule(
  name: string,
  m: YosysModule,
  allModules: Set<string>,
  sources: Record<string, string>,
): IRModule {
  const ports: IRPort[] = Object.entries(m.ports).map(([pname, p]) => ({
    name: pname,
    direction: p.direction,
    bits: p.bits,
    offset: p.offset ?? 0,
    upto: !!p.upto,
  }));

  const nets: IRNet[] = Object.entries(m.netnames).map(([nname, n]) => ({
    name: nname,
    hidden: !!n.hide_name,
    bits: n.bits,
    offset: n.offset ?? 0,
    upto: !!n.upto,
    src: parseSrc(n.attributes?.src),
  }));

  // bit -> public net name, used to build readable fingerprints.
  const bitName = new Map<number, string>();
  for (const n of nets) {
    if (n.hidden) continue;
    for (const b of n.bits) if (typeof b === 'number' && !bitName.has(b)) bitName.set(b, n.name);
  }

  const used = new Map<string, number>();
  const cells: IRCell[] = Object.entries(m.cells).map(([cname, c]) => {
    const hidden = !!c.hide_name || cname.startsWith('$');
    const src = parseSrc(c.attributes?.src);
    const directions = cellDirections(c.type, c.connections, c.port_directions);
    let base: string;
    if (!hidden) {
      base = cname;
    } else {
      // Fingerprint: type + the expression text it came from + named signals it touches.
      // Comments are not part of what a cell computes: adding one must not change its ID.
      const text = sourceText(sources, src[0]);
      const expr = text ? normalizeWhitespace(stripComments(text)) : undefined;
      // A register (or any cell made from a whole always block) is told apart by what it drives:
      // the block's text changes with every statement or comment in it, and is the same for every
      // register the block makes. Edits saved for `$dff{Q=q}` then survive changes to the block.
      const drives =
        REGISTER_CELL.test(c.type) || PROCESS_TEXT.test(expr ?? '') ? drivenSignals(nets, c.connections, directions, expr ?? '') : '';
      const touched = Object.keys(c.connections)
        .sort()
        .map((p) => {
          const bits = c.connections[p];
          // A constant operand tells apart cells that read the same signals, such as the `sel == 2'd0`,
          // `sel == 2'd1`… compares of a case statement (Yosys gives them no source text). Without it
          // they differ only by Yosys' cell order, so after the case items are reordered an edit
          // saved for one of them would move or hide another.
          if (bits.length > 0 && bits.every((b) => typeof b !== 'number')) return `${p}=${formatConst(bits)}`;
          const names = new Set<string>();
          for (const b of bits) if (typeof b === 'number' && bitName.has(b)) names.add(bitName.get(b)!);
          return `${p}=${[...names].join('+')}`;
        })
        .join(',');
      base = `${c.type}{${drives || (expr ?? touched)}}`;
    }
    const n = used.get(base) ?? 0;
    used.set(base, n + 1);
    const id = n === 0 ? base : `${base}#${n}`;
    const isInstance = allModules.has(c.type);
    return {
      id,
      name: cname,
      hidden,
      type: c.type,
      isInstance,
      moduleName: isInstance ? c.type : undefined,
      parameters: c.parameters ?? {},
      directions,
      connections: c.connections,
      src,
    };
  });

  return {
    name,
    displayName: displayModuleName(name),
    isTop: m.attributes?.top !== undefined && /1/.test(m.attributes.top),
    ports,
    cells,
    nets,
    src: parseSrc(m.attributes?.src),
  };
}

/**
 * Convert Yosys JSON into the IR.
 * @param sources file name -> Verilog text, used for stable IDs and code highlighting.
 */
export function buildDesign(json: YosysDesign, sources: Record<string, string> = {}): IRDesign {
  const names = new Set(Object.keys(json.modules));
  const modules: Record<string, IRModule> = {};
  for (const [name, m] of Object.entries(json.modules)) {
    // Skip blackbox / library cells Yosys may include.
    if (m.attributes?.blackbox && /1/.test(m.attributes.blackbox)) continue;
    modules[name] = buildModule(name, m, names, sources);
  }
  let top = Object.values(modules).find((m) => m.isTop)?.name;
  if (!top) {
    // Fall back to a module nobody instantiates.
    const instantiated = new Set<string>();
    for (const m of Object.values(modules)) for (const c of m.cells) if (c.isInstance) instantiated.add(c.type);
    top = Object.keys(modules).find((n) => !instantiated.has(n)) ?? Object.keys(modules)[0];
  }
  return { modules, top: top ?? '' };
}

export function buildHierarchy(design: IRDesign, moduleName = design.top, instance = moduleName, depth = 0): HierarchyNode {
  const m = design.modules[moduleName];
  const children: HierarchyNode[] = [];
  if (m && depth < 64) {
    for (const c of m.cells) {
      if (c.isInstance && design.modules[c.type]) children.push(buildHierarchy(design, c.type, c.name, depth + 1));
    }
  }
  return { instance, module: moduleName, children };
}

/** Bits driven from outside the module: its input and inout port bits. */
export function inputPortBits(m: IRModule): Set<number> {
  const out = new Set<number>();
  for (const p of m.ports) if (p.direction !== 'output') for (const b of p.bits) if (typeof b === 'number') out.add(b);
  return out;
}

/** Width of a port or net in bits. */
export function widthOf(x: { bits: Bit[] }): number {
  return x.bits.length;
}

/** `name[hi:lo]` for a slice of a net, or just `name` when it covers the whole net. */
export function sliceLabel(net: IRNet, lo: number, hi: number): string {
  if (lo === 0 && hi === net.bits.length - 1) return net.name;
  const a = net.upto ? net.offset + (net.bits.length - 1 - hi) : net.offset + hi;
  const b = net.upto ? net.offset + (net.bits.length - 1 - lo) : net.offset + lo;
  return a === b ? `${net.name}[${a}]` : `${net.name}[${a}:${b}]`;
}

/** Format constant bits (LSB first) the way designers write them: 4'd2, 1'b0, 3'bx01. */
export function formatConst(bits: Bit[]): string {
  const w = bits.length;
  if (bits.every((b) => b === '0' || b === '1')) {
    if (w === 1) return `1'b${bits[0]}`;
    let v = 0n;
    for (let i = w - 1; i >= 0; i--) v = (v << 1n) | (bits[i] === '1' ? 1n : 0n);
    return `${w}'d${v.toString()}`;
  }
  return `${w}'b${[...bits].reverse().join('')}`;
}
